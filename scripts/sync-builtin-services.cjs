const fs = require('fs');
const path = require('path');

const RUST_FILE = path.join(
  __dirname,
  '../src-tauri/src/mcp/builtin/service_id.rs',
);
const TS_FILE = path.join(
  __dirname,
  '../src/lib/generated/builtin-services.ts',
);

function sync() {
  console.log('🔄 Syncing builtin services from Rust to TypeScript...');

  if (!fs.existsSync(RUST_FILE)) {
    console.error(`❌ Rust file not found: ${RUST_FILE}`);
    process.exit(1);
  }

  const content = fs.readFileSync(RUST_FILE, 'utf8');

  // Extract variants and their canonical names from BUILTIN_SERVICE_REGISTRY
  // Pattern: BuiltinServiceEntry { variant: BuiltinServiceId::Variant, canonical: "id", optional: false }
  const registryMatch = content.match(
    /pub const BUILTIN_SERVICE_REGISTRY: &\[BuiltinServiceEntry\] = &\[([\s\S]*?)\];/,
  );

  if (!registryMatch) {
    console.error('❌ Could not find BUILTIN_SERVICE_REGISTRY in Rust file');
    process.exit(1);
  }

  const entriesText = registryMatch[1];
  const entryRegex = /canonical:\s*"([^"]+)",\s*optional:\s*(true|false),/g;
  const services = [];
  let match;

  while ((match = entryRegex.exec(entriesText)) !== null) {
    services.push({
      canonical: match[1],
      optional: match[2] === 'true',
    });
  }

  // Extract all supported aliases from from_alias(). At the moment this matches the
  // canonical names exactly, but the generated file should reflect the real parser.
  const allAliases = new Set();
  const armsMatch = content.match(
    /match alias\.trim\(\)\.to_lowercase\(\)\.as_str\(\) \{([\s\S]*?)_ => None/,
  );
  if (armsMatch) {
    const armsText = armsMatch[1];
    const armRegex = /"([^"]+)"/g;
    while ((match = armRegex.exec(armsText)) !== null) {
      allAliases.add(match[1]);
    }
  }

  if (services.length === 0) {
    console.error('❌ No services found in registry');
    process.exit(1);
  }

  const coreServices = services
    .filter((s) => !s.optional)
    .map((s) => s.canonical);
  const optionalServices = services
    .filter((s) => s.optional)
    .map((s) => s.canonical);

  const tsContent = `/**
 * ⚠️ AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
 * This file is generated by scripts/sync-builtin-services.cjs
 * Source: src-tauri/src/mcp/builtin/service_id.rs
 */

/** Canonical names of all builtin services */
export const BUILTIN_SERVICE_CANONICAL_NAMES = [
${services.map((s) => `  '${s.canonical}',`).join('\n')}
] as const;

export type BuiltinServiceCanonicalName = typeof BUILTIN_SERVICE_CANONICAL_NAMES[number];

/** All recognized builtin service aliases */
export const ALL_BUILTIN_SERVICE_ALIASES = [
${Array.from(allAliases)
  .map((a) => `  '${a}',`)
  .join('\n')}
] as const;

export type BuiltinServiceAlias = typeof ALL_BUILTIN_SERVICE_ALIASES[number];

/** Core builtin services (optional: false in Rust) */
export const CORE_BUILTIN_SERVICE_ALIASES = [
${coreServices.map((s) => `  '${s}',`).join('\n')}
] as const;

/** Optional builtin services (optional: true in Rust) */
export const OPTIONAL_BUILTIN_SERVICE_ALIASES = [
${optionalServices.map((s) => `  '${s}',`).join('\n')}
] as const;
`;

  const dir = path.dirname(TS_FILE);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(TS_FILE, tsContent);
  console.log(
    `✅ Generated ${services.length} services and ${allAliases.size} aliases to ${TS_FILE}`,
  );
}

sync();
