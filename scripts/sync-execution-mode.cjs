const fs = require('fs');
const path = require('path');

const RUST_FILE = path.join(__dirname, '../src-tauri/src/execution_mode.rs');
const TS_FILE = path.join(__dirname, '../src/lib/generated/execution-mode.ts');

function sync() {
  console.log('🔄 Syncing execution mode from Rust to TypeScript...');

  if (!fs.existsSync(RUST_FILE)) {
    console.error(`❌ Rust file not found: ${RUST_FILE}`);
    process.exit(1);
  }

  const content = fs.readFileSync(RUST_FILE, 'utf8');
  const valuesMatch = content.match(
    /pub const EXECUTION_MODE_DB_VALUES: &\[&str\] = &\[(.*?)\];/s,
  );

  if (!valuesMatch) {
    console.error('❌ Could not find EXECUTION_MODE_DB_VALUES in Rust file');
    process.exit(1);
  }

  const values = [...valuesMatch[1].matchAll(/"([^"]+)"/g)].map(
    (match) => match[1],
  );

  if (values.length === 0) {
    console.error('❌ No execution mode values found in Rust file');
    process.exit(1);
  }

  const tsContent = `/**
 * ⚠️ AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
 * This file is generated by scripts/sync-execution-mode.cjs
 * Source: src-tauri/src/execution_mode.rs
 */

/** Canonical execution mode values shared with the Rust backend and SQLite schema */
export const EXECUTION_MODE_VALUES = [
${values.map((value) => `  '${value}',`).join('\n')}
] as const;

export type ExecutionMode = (typeof EXECUTION_MODE_VALUES)[number];

export const DEFAULT_EXECUTION_MODE: ExecutionMode = 'normal';

export function isExecutionMode(value: unknown): value is ExecutionMode {
  return (
    typeof value === 'string' &&
    (EXECUTION_MODE_VALUES as readonly string[]).includes(value)
  );
}

export function normalizeExecutionMode(value: unknown): ExecutionMode {
  return isExecutionMode(value) ? value : DEFAULT_EXECUTION_MODE;
}
`;

  const dir = path.dirname(TS_FILE);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(TS_FILE, tsContent);
  console.log(
    `✅ Generated ${values.length} execution mode values to ${TS_FILE}`,
  );
}

sync();
